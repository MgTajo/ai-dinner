const byId = new Map(restaurants.map((r) => [r.id, r]));
const itemsById = new Map(restaurants.flatMap((r) => r.menu.map((m) => [m.id, { restaurant: r, item: m }] as const)));

export function restaurantById(id: string): Restaurant {
  const r = byId.get(id);
  if (!r) throw new Error(`Unknown restaurant ${id}`);
  return r;
}

export function itemById(id: string): { restaurant: Restaurant; item: MenuItem } {
  const found = itemsById.get(id);
  if (!found) throw new Error(`Unknown menu item ${id}`);
  return found;
}

